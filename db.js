const fs = require('fs');
const path = require('path');
const { Pool } = require('pg');
const bcrypt = require('bcryptjs');

if (!process.env.DATABASE_URL) console.warn('DATABASE_URL no está configurada. La aplicación necesita PostgreSQL para iniciar.');

const pool = new Pool({
  connectionString: process.env.DATABASE_URL,
  ssl: process.env.DATABASE_URL ? { rejectUnauthorized: false } : undefined
});

// Capa de compatibilidad para conservar la API callback que usa server.js.
let queue = Promise.resolve();
let readyPromise = Promise.resolve();
let transactionClient = null;

function enqueue(task) {
  const run = queue.then(() => readyPromise).then(task, task);
  queue = run.catch(() => {});
  return run;
}

function convertSql(sql) {
  let text = String(sql || '').trim();
  text = text.replace(/INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT/gi, 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
  text = text.replace(/\bDATETIME\b/gi, 'TIMESTAMP');
  text = text.replace(/\bREAL\b/gi, 'DOUBLE PRECISION');
  text = text.replace(/datetime\(\s*'now'\s*,\s*'-5 minutes'\s*\)/gi, "(CURRENT_TIMESTAMP - INTERVAL '5 minutes')");
  text = text.replace(/datetime\(\s*fecha_registro\s*\)/gi, 'fecha_registro');
  text = text.replace(
    /INSERT\s+OR\s+REPLACE\s+INTO\s+stock_inventario\s*\(\s*id\s*,\s*nombre\s*,\s*stock\s*,\s*unidad\s*,\s*actualizado_en\s*\)\s*VALUES\s*\(([^)]*)\)/i,
    'INSERT INTO stock_inventario (id, nombre, stock, unidad, actualizado_en) VALUES ($1, $2, $3, $4, $5) ON CONFLICT (id) DO UPDATE SET nombre=EXCLUDED.nombre, stock=EXCLUDED.stock, unidad=EXCLUDED.unidad, actualizado_en=EXCLUDED.actualizado_en'
  );
  let index = 0;
  text = text.replace(/\?/g, () => `$${++index}`);
  return text;
}

function callbackResult(result) {
  return { lastID: result.rows && result.rows[0] ? result.rows[0].id : undefined, changes: result.rowCount || 0 };
}

function runQuery(sql, params, callback) {
  return enqueue(async () => {
    let query = convertSql(sql);
    if (/^INSERT\s+/i.test(query) && !/\bRETURNING\b/i.test(query)) query += ' RETURNING id';
    try {
      if (/^BEGIN(?:\s+TRANSACTION)?$/i.test(query)) {
        if (!transactionClient) { transactionClient = await pool.connect(); await transactionClient.query('BEGIN'); }
        if (callback) callback.call({ lastID: undefined, changes: 0 }, null);
        return { lastID: undefined, changes: 0 };
      }
      if (/^COMMIT$/i.test(query)) {
        if (transactionClient) { await transactionClient.query('COMMIT'); transactionClient.release(); transactionClient = null; }
        if (callback) callback.call({ lastID: undefined, changes: 0 }, null);
        return { lastID: undefined, changes: 0 };
      }
      if (/^ROLLBACK$/i.test(query)) {
        if (transactionClient) { await transactionClient.query('ROLLBACK'); transactionClient.release(); transactionClient = null; }
        if (callback) callback.call({ lastID: undefined, changes: 0 }, null);
        return { lastID: undefined, changes: 0 };
      }
      const result = await (transactionClient || pool).query(query, params || []);
      const info = callbackResult(result);
      if (callback) callback.call(info, null);
      return info;
    } catch (error) {
      if (callback) callback.call({ lastID: undefined, changes: 0 }, error);
      return null;
    }
  });
}

const db = {
  run(sql, params, callback) {
    if (typeof params === 'function') { callback = params; params = []; }
    runQuery(sql, params || [], callback);
    return this;
  },
  all(sql, params, callback) {
    if (typeof params === 'function') { callback = params; params = []; }
    enqueue(async () => {
      try { const result = await (transactionClient || pool).query(convertSql(sql), params || []); callback?.(null, result.rows || []); }
      catch (error) { callback?.(error); }
    });
    return this;
  },
  get(sql, params, callback) {
    if (typeof params === 'function') { callback = params; params = []; }
    enqueue(async () => {
      try { const result = await (transactionClient || pool).query(convertSql(sql), params || []); callback?.(null, result.rows[0]); }
      catch (error) { callback?.(error); }
    });
    return this;
  },
  prepare(sql) {
    return {
      run(...args) {
        let callback = null;
        if (typeof args[args.length - 1] === 'function') callback = args.pop();
        runQuery(sql, args, callback);
        return this;
      },
      finalize(callback) { callback?.(null); }
    };
  },
  serialize(callback) { callback(); return this; },
  close(callback) { pool.end().then(() => callback?.(null)).catch(err => callback?.(err)); }
};

function extractVariable(source, variableName) {
  const marker = `const ${variableName} = `;
  const start = source.indexOf(marker);
  if (start === -1) throw new Error(`No se encontró ${variableName} en db-seed-source.js`);
  const valueStart = start + marker.length;
  if (source[valueStart] !== '[') throw new Error(`${variableName} no es un array`);
  let depth = 0, quote = null, escaped = false, end = -1;
  for (let i = valueStart; i < source.length; i++) {
    const ch = source[i];
    if (quote) {
      if (escaped) escaped = false;
      else if (ch === '\\') escaped = true;
      else if (ch === quote) quote = null;
      continue;
    }
    if (ch === "'" || ch === '"' || ch === '`') { quote = ch; continue; }
    if (ch === '[') depth++;
    if (ch === ']') { depth--; if (depth === 0) { end = i + 1; break; } }
  }
  if (end === -1) throw new Error(`No se pudo cerrar ${variableName}`);
  return Function(`"use strict"; return (${source.slice(valueStart, end)});`)();
}

async function initializeDatabase() {
  if (!process.env.DATABASE_URL) return;

  await pool.query(`CREATE TABLE IF NOT EXISTS productos (
    id TEXT PRIMARY KEY, nombre TEXT NOT NULL, categoria TEXT NOT NULL,
    precio DOUBLE PRECISION NOT NULL DEFAULT 0, precio_x25 DOUBLE PRECISION,
    precio_x50 DOUBLE PRECISION, precio_x100 DOUBLE PRECISION, precio_unidad DOUBLE PRECISION)`);

  await pool.query(`CREATE TABLE IF NOT EXISTS formulas_inventario (
    id TEXT PRIMARY KEY, nombre TEXT NOT NULL, categoria TEXT NOT NULL,
    unidad TEXT NOT NULL DEFAULT 'unidad', cantidad_base INTEGER NOT NULL DEFAULT 100,
    formula TEXT NOT NULL DEFAULT '{}', descripcion TEXT DEFAULT '')`);

  await pool.query(`CREATE TABLE IF NOT EXISTS stock_inventario (
    id TEXT PRIMARY KEY, nombre TEXT NOT NULL, stock DOUBLE PRECISION NOT NULL DEFAULT 0,
    unidad TEXT NOT NULL DEFAULT 'kg', actualizado_en TIMESTAMP DEFAULT CURRENT_TIMESTAMP)`);

  await pool.query(`CREATE TABLE IF NOT EXISTS usuarios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario TEXT NOT NULL,
    nombre TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    rol TEXT NOT NULL CHECK (rol IN ('admin', 'colaborador')),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    ultimo_login TIMESTAMP,
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
  )`);
  await pool.query(`CREATE UNIQUE INDEX IF NOT EXISTS usuarios_usuario_lower_uidx ON usuarios (LOWER(usuario))`);

  const bootstrapUsuario = String(process.env.ADMIN_USERNAME || 'dchelis').trim();
  const bootstrapNombre = String(process.env.ADMIN_NAME || 'Administrador').trim() || 'Administrador';
  const bootstrapHashConfigurado = String(process.env.ADMIN_PASSWORD_HASH || '').trim();
  const bootstrapPassword = String(process.env.ADMIN_PASSWORD || '');
  const bootstrapHash = bootstrapHashConfigurado || (bootstrapPassword ? bcrypt.hashSync(bootstrapPassword, 12) : '');

  if (bootstrapUsuario && bootstrapHash) {
    await pool.query(
      `INSERT INTO usuarios (usuario, nombre, password_hash, rol, activo)
       SELECT $1, $2, $3, 'admin', TRUE
       WHERE NOT EXISTS (SELECT 1 FROM usuarios WHERE LOWER(usuario) = LOWER($1))`,
      [bootstrapUsuario, bootstrapNombre, bootstrapHash]
    );
  }

  await pool.query(`CREATE TABLE IF NOT EXISTS pedidos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, codigo TEXT UNIQUE NOT NULL,
    tipo_cliente TEXT NOT NULL, cliente_nombre TEXT NOT NULL, celular TEXT NOT NULL,
    monto_total DOUBLE PRECISION NOT NULL, adelanto DOUBLE PRECISION NOT NULL, metodo_pago TEXT NOT NULL,
    fecha_recoge TEXT NOT NULL, hora_recoge TEXT NOT NULL, dedicatoria TEXT DEFAULT '', foto_torta TEXT DEFAULT '',
    tipo_comprobante TEXT DEFAULT '', numero_documento TEXT DEFAULT '', nro_operacion TEXT DEFAULT '',
    estado TEXT DEFAULT 'Registrado', fecha_registro TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    registrado_en TIMESTAMP, despachado_por TEXT DEFAULT '')`);

  await pool.query(`ALTER TABLE pedidos ADD COLUMN IF NOT EXISTS registrado_en TIMESTAMP`);
  await pool.query(`ALTER TABLE pedidos ADD COLUMN IF NOT EXISTS despachado_por TEXT DEFAULT ''`);

  await pool.query(`CREATE TABLE IF NOT EXISTS detalles_pedido (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, pedido_id INTEGER NOT NULL REFERENCES pedidos(id) ON DELETE CASCADE,
    producto_nombre TEXT NOT NULL, cantidad INTEGER NOT NULL, subtotal DOUBLE PRECISION NOT NULL, paquetes TEXT DEFAULT '{}',
    foto_torta TEXT DEFAULT '')`);
  await pool.query(`ALTER TABLE detalles_pedido ADD COLUMN IF NOT EXISTS foto_torta TEXT DEFAULT ''`);

  const source = fs.readFileSync(path.join(__dirname, 'db-seed-source.js'), 'utf8');
  const productos = extractVariable(source, 'productosIniciales');
  const formulas = extractVariable(source, 'formulasBase');
  const stock = extractVariable(source, 'stockInicial');

  for (const p of productos) {
    await pool.query(`INSERT INTO productos (id,nombre,categoria,precio,precio_x25,precio_x50,precio_x100,precio_unidad)
      VALUES ($1,$2,$3,$4,$5,$6,$7,$8)
      ON CONFLICT (id) DO UPDATE SET nombre=EXCLUDED.nombre,categoria=EXCLUDED.categoria,precio=EXCLUDED.precio,
      precio_x25=EXCLUDED.precio_x25,precio_x50=EXCLUDED.precio_x50,precio_x100=EXCLUDED.precio_x100,precio_unidad=EXCLUDED.precio_unidad`, p);
  }

  await pool.query(`DELETE FROM productos WHERE id IN (
    'dulce_mousse_fresa_maracuya_lucuma', 'fam_mousse_fresa_maracuya', 'fam_pye_manzana_limon', 'fam_keke_variado',
    'torta_chantilly_30_35', 'torta_chantilly_80', 'torta_chantilly_tres_leches', 'torta_chantilly_adicional',
    'dulce_tartaleta_durazno_fresa', 'dulce_tartaleta_sauco_lucuma', 'dulce_tortita_helada_selva',
    'extra_torta_chocolate', 'extra_torta_selva_negra', 'extra_torta_helada', 'extra_torta_mousse_fresa',
    'extra_torta_mousse_maracuya', 'extra_torta_pye_manzana', 'extra_torta_pye_limon', 'extra_torta_keke_pasas',
    'extra_torta_keke_vainilla', 'extra_torta_keke_marmol', 'extra_torta_keke_castana')`);

  for (const f of formulas) {
    await pool.query(`INSERT INTO formulas_inventario (id,nombre,categoria,unidad,cantidad_base,formula,descripcion)
      VALUES ($1,$2,$3,$4,$5,$6,$7)
      ON CONFLICT (id) DO UPDATE SET nombre=EXCLUDED.nombre,categoria=EXCLUDED.categoria,unidad=EXCLUDED.unidad,
      cantidad_base=EXCLUDED.cantidad_base,formula=EXCLUDED.formula,descripcion=EXCLUDED.descripcion`,
      [f.id, f.nombre, f.categoria, f.unidad, f.cantidad_base, f.formula, f.descripcion]);
  }

  for (const [id, nombre, stockValue, unidad] of stock) {
    await pool.query(`INSERT INTO stock_inventario (id,nombre,stock,unidad,actualizado_en)
      VALUES ($1,$2,$3,$4,$5) ON CONFLICT (id) DO NOTHING`,
      [id, nombre, stockValue, unidad, new Date().toISOString()]);
  }

  console.log('PostgreSQL conectado y tablas iniciales listas.');
}

db.ready = initializeDatabase();
readyPromise = db.ready;
db.ready.catch((error) => { console.error('Error inicializando PostgreSQL:', error); process.exitCode = 1; });

module.exports = db;
